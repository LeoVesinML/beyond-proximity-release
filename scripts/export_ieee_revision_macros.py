#!/usr/bin/env python3
"""Export auditable IEEE Access LaTeX macros from frozen result JSON."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]


def _read(path: str) -> dict[str, Any]:
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def _pct(value: float) -> str:
    return f"{100.0 * value:.1f}"


def _method(rows: list[dict[str, Any]], name: str, n: int) -> dict[str, Any]:
    return next(row for row in rows if row["method"] == name and row["query_count"] == n)


def _write_hierarchy_grid_table() -> None:
    source = ROOT / "outputs/ieee_revision/hierarchy_scorer_grid_v1/hierarchy_scorer_grid_summary.json"
    if not source.is_file():
        return
    payload = json.loads(source.read_text(encoding="utf-8"))
    by_key = {
        (row["variant"], row["scorer"], int(row["budget"])): row
        for row in payload["aggregate"]
    }
    variant_labels = {
        "manual_reference": "Manual reference",
        "pose_only": "Pose only",
        "pose_semantic_merge": "Pose + semantic",
        "raw_rgbd": "Raw RGB-D",
    }
    scorer_labels = {"lexical": "Lexical", "bge": "BGE", "clip": "CLIP"}
    lines = [
        "% Generated by scripts/export_ieee_revision_macros.py.\n",
        "\\begin{table*}[!t]\n",
        "\\centering\n",
        "\\caption{Matched hierarchy--scorer grid on 125 verified positives. Every cell retains the stated number of views; values are hit@1 / hit@3.}\n",
        "\\label{tab:hierarchy-grid}\n",
        "\\small\n",
        "\\begin{tabular}{llccc}\n",
        "\\toprule\n",
        "Hierarchy & Scorer & $k=3$ & $k=6$ & $k=12$ \\\\\n",
        "\\midrule\n",
    ]
    for variant_index, variant in enumerate(variant_labels):
        for scorer_index, scorer in enumerate(scorer_labels):
            cells = []
            for budget in (3, 6, 12):
                row = by_key[(variant, scorer, budget)]
                cells.append(f"{row['hit_at_1']:.3f} / {row['hit_at_3']:.3f}")
            variant_text = variant_labels[variant] if scorer_index == 0 else ""
            lines.append(
                f"{variant_text} & {scorer_labels[scorer]} & " + " & ".join(cells) + " \\\\\n"
            )
        if variant_index < len(variant_labels) - 1:
            lines.append("\\addlinespace[2pt]\n")
    lines.extend([
        "\\bottomrule\n",
        "\\end{tabular}\n",
        "\\end{table*}\n",
    ])
    target = ROOT / "papers/ieee-access/tables/hierarchy_scorer_grid.tex"
    target.write_text("".join(lines), encoding="utf-8")


def main() -> None:
    lexical = _read("outputs/ieee_revision/recall_frontier_v1/frontier_summary.json")
    bge = _read("outputs/ieee_revision/bge_frontier_v1/bge_frontier_summary.json")
    scale = _read("outputs/ieee_revision/public_scale_ann_v1/scale_ann_summary.json")
    predicted = _read("outputs/ieee_revision/predicted_map_pair_v1/predicted_map_pair_summary.json")
    lex = lexical["operating_point"]
    lex_flat = lexical["flat_test"]
    emb = bge["operating_point"]
    emb_flat = bge["flat_test"]
    scale_rows = scale["summaries"]
    full_n = max(row["collection_size"] for row in scale_rows)
    scale_flat = next(row for row in scale_rows if row["method"] == "flat_dense_exact" and row["collection_size"] == full_n)
    scale_hnsw = next(row for row in scale_rows if row["method"] == "hnsw_dense" and row["collection_size"] == full_n)
    scale_scene = next(row for row in scale_rows if row["method"] == "scene_scoped_dense_exact" and row["collection_size"] == full_n)
    scan_flat = _method(predicted["summaries"], "flat_bge_predicted_map", 48)
    scan_graph = _method(predicted["summaries"], "graph_bge_predicted_map", 48)
    rep_flat = _method(predicted["summaries"], "flat_bge_predicted_map", 56)
    rep_graph = _method(predicted["summaries"], "graph_bge_predicted_map", 56)
    values = {
        "LexTestN": "75", "LexHitOne": f"{lex['hit_at_1']:.3f}", "LexHitThree": f"{lex['hit_at_3']:.3f}",
        "LexMRR": f"{lex['mrr']:.3f}", "LexFlatHitOne": f"{lex_flat['hit_at_1']:.3f}",
        "LexFlatHitThree": f"{lex_flat['hit_at_3']:.3f}", "LexFlatMRR": f"{lex_flat['mrr']:.3f}",
        "LexRecords": f"{lex['mean_records_checked']:.2f}", "LexFlatRecords": f"{lex_flat['mean_records_checked']:.1f}",
        "LexRecordSavings": _pct(lex["record_savings_vs_flat"]), "LexTokenSavings": _pct(lex["context_token_savings_vs_flat"]),
        "LexContextTokens": f"{lex['mean_serialized_context_tokens']:.0f}", "LexFlatContextTokens": f"{lex_flat['mean_serialized_context_tokens']:.0f}",
        "LexMrrDeltaLow": f"{lex['paired_mrr_difference']['ci_95']['low']:.3f}", "LexMrrDeltaHigh": f"{lex['paired_mrr_difference']['ci_95']['high']:.3f}",
        "BgeHitOne": f"{emb['hit_at_1']:.3f}", "BgeHitThree": f"{emb['hit_at_3']:.3f}", "BgeMRR": f"{emb['mrr']:.3f}",
        "BgeFlatHitOne": f"{emb_flat['hit_at_1']:.3f}", "BgeFlatHitThree": f"{emb_flat['hit_at_3']:.3f}", "BgeFlatMRR": f"{emb_flat['mrr']:.3f}",
        "BgeRecords": f"{emb['mean_records_checked']:.2f}", "BgeFlatRecords": f"{emb_flat['mean_records_checked']:.1f}",
        "BgeRecordSavings": _pct(emb["record_savings_vs_flat"]), "BgeTokenSavings": _pct(emb["context_token_savings_vs_flat"]),
        "ScaleQueryN": str(sum(row["query_count"] for row in scale_rows if row["method"] == "flat_dense_exact")),
        "ScaleRecordN": f"{full_n:,}", "ScaleSceneN": f"{scale['data_manifest']['scene_count']:,}",
        "ScaleObjectN": f"{scale['data_manifest']['object_count']:,}",
        "ScaleFlatHitThree": f"{scale_flat['hit_at_3']:.3f}", "ScaleHnswHitThree": f"{scale_hnsw['hit_at_3']:.3f}",
        "ScaleSceneHitThree": f"{scale_scene['hit_at_3']:.3f}", "ScaleFlatLatency": f"{scale_flat['median_latency_ms']:.2f}",
        "ScaleHnswLatency": f"{scale_hnsw['median_latency_ms']:.2f}", "ScaleSceneLatency": f"{scale_scene['median_latency_ms']:.3f}",
        "ScaleSceneRecords": f"{scale_scene['mean_scored_records']:.1f}",
        "ScanPredAcc": f"{scan_graph['acc_at_0_25']:.3f}", "ScanPredAccFifty": f"{scan_graph['acc_at_0_50']:.3f}",
        "ScanPredRecallThree": f"{scan_graph['recall_at_3_iou_0_25']:.3f}", "ScanPredReduction": _pct(scan_graph['checked_object_reduction_vs_flat']),
        "ScanPredFlatObjects": f"{scan_flat['mean_checked_objects']:.1f}",
        "RepPredAcc": f"{rep_graph['acc_at_0_25']:.3f}", "RepPredAccFifty": f"{rep_graph['acc_at_0_50']:.3f}",
        "RepPredRecallThree": f"{rep_graph['recall_at_3_iou_0_25']:.3f}", "RepPredReduction": _pct(rep_graph['checked_object_reduction_vs_flat']),
        "RepPredFlatObjects": f"{rep_flat['mean_checked_objects']:.1f}",
    }
    agent_path = ROOT / "outputs/ieee_revision/qwen25_15b_pair_v1/metrics_summary.json"
    if agent_path.is_file():
        agent = json.loads(agent_path.read_text(encoding="utf-8"))
        for prefix, name in (("AgentFlat", "flat_instruction"), ("AgentGraph", "graph_instruction")):
            row = agent["methods"][name]
            values.update({
                f"{prefix}HitOne": f"{row['hit_at_1']:.3f}", f"{prefix}HitThree": f"{row['hit_at_3']:.3f}",
                f"{prefix}MRR": f"{row['mrr']:.3f}", f"{prefix}Views": f"{row['mean_views_checked']:.2f}",
                f"{prefix}Tokens": f"{row['mean_total_tokens']:.0f}",
                f"{prefix}InputTokens": f"{row['mean_input_tokens']:.0f}",
                f"{prefix}TotalTokens": f"{row['total_tokens']:,}",
                f"{prefix}Calls": f"{row['mean_model_calls']:.0f}",
                f"{prefix}Latency": f"{row['mean_latency_ms'] / 1000.0:.2f}",
            })
        comparison = agent["comparison"]
        values.update({
            "AgentInputReduction": f"{comparison['input_token_reduction_pct']:.1f}",
            "AgentViewReduction": f"{comparison['views_reduction_pct']:.1f}",
            "AgentHitOneDelta": f"{comparison['hit_at_1']['difference_graph_minus_flat']:.3f}",
            "AgentHitOneLow": f"{comparison['hit_at_1']['ci_95'][0]:.3f}",
            "AgentHitOneHigh": f"{comparison['hit_at_1']['ci_95'][1]:.3f}",
            "AgentHitThreeDelta": f"{comparison['hit_at_3']['difference_graph_minus_flat']:.3f}",
            "AgentHitThreeLow": f"{comparison['hit_at_3']['ci_95'][0]:.3f}",
            "AgentHitThreeHigh": f"{comparison['hit_at_3']['ci_95'][1]:.3f}",
            "AgentMrrDelta": f"{comparison['mrr']['difference_graph_minus_flat']:.3f}",
            "AgentMrrLow": f"{comparison['mrr']['ci_95'][0]:.3f}",
            "AgentMrrHigh": f"{comparison['mrr']['ci_95'][1]:.3f}",
        })
    target = ROOT / "papers/ieee-access/tables/ieee_revision_macros.tex"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("% Generated by scripts/export_ieee_revision_macros.py.\n" + "".join(
        f"\\newcommand{{\\{name}}}{{{value}}}\n" for name, value in values.items()
    ), encoding="utf-8")
    _write_hierarchy_grid_table()
    print(target)


if __name__ == "__main__":
    main()
